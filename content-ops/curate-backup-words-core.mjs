/**
 * The rules that turn the EFF Large Wordlist into the backup word list, as pure functions with no file
 * access, so the runner stays thin and every rule is testable on a few lines of text.
 *
 * The source's shape is read from the file, never assumed: a dice index with a digit outside 1-6, a
 * carriage return from a careless download, or a repeated word would otherwise flow into a list that is
 * frozen for the life of the backup format. The removals are data (a reviewed file of word and reason), not
 * judgment buried in code, and a typo in it fails here instead of silently keeping a word that was meant
 * to go.
 */

import { createHash } from 'node:crypto';

/** @type {readonly string[]} */
export const REMOVAL_REASONS = Object.freeze([
	'hyphen',
	'alternate',
	'brand',
	'drug',
	'proper',
	'offensive'
]);

// Six words must carry at least 77 bits: 6 * log2(N) >= 77 needs N >= 7,299 (N = 7,298 gives 76.9997).
export const MIN_WORDS = 7299;
export const SOURCE_LINES = 7776;

const TAB = String.fromCharCode(9);
const LF = String.fromCharCode(10);
const BACKSLASH = String.fromCharCode(92);
// The line feed as it is written inside a string literal: two characters, not a line break.
const LF_ESCAPE = BACKSLASH + 'n';

const DICE_INDEX = /^[1-6]{5}$/;
// Printable ASCII with no space: a stray carriage return, space or control character fails the shape.
const TOKEN = /^[!-~]+$/;
const LETTERS = /^[a-z]+$/;

/**
 * The lines of a text that ends in exactly one line feed, or null.
 * @param {string} text
 * @returns {string[] | null}
 */
function linesOf(text) {
	if (!text.endsWith(LF)) return null;
	return text.slice(0, -1).split(LF);
}

/**
 * @param {string} text
 * @param {number} [lines] how many lines the file must hold; only a test passes a smaller number
 * @returns {string[]} the words in file order
 */
export function parseSource(text, lines = SOURCE_LINES) {
	const rows = linesOf(text);
	if (rows === null || rows.length !== lines) throw new Error('E_SOURCE_SHAPE');
	/** @type {string[]} */
	const words = [];
	for (const row of rows) {
		const [index, word, ...extra] = row.split(TAB);
		if (index === undefined || word === undefined || extra.length > 0) {
			throw new Error('E_SOURCE_SHAPE');
		}
		if (!DICE_INDEX.test(index) || !TOKEN.test(word)) throw new Error('E_SOURCE_SHAPE');
		words.push(word);
	}
	if (new Set(words).size !== words.length) throw new Error('E_SOURCE_SHAPE');
	return words;
}

/**
 * @param {string} text
 * @param {readonly string[]} sourceWords
 * @returns {Set<string>} the removed words
 */
export function parseRemovals(text, sourceWords) {
	const rows = linesOf(text);
	if (rows === null) throw new Error('E_REMOVAL_SHAPE');
	const known = new Set(sourceWords);
	/** @type {Set<string>} */
	const removed = new Set();
	for (const row of rows) {
		const [word, reason, ...extra] = row.split(TAB);
		if (word === undefined || reason === undefined || extra.length > 0) {
			throw new Error('E_REMOVAL_SHAPE');
		}
		if (!TOKEN.test(word) || !TOKEN.test(reason)) throw new Error('E_REMOVAL_SHAPE');
		if (!REMOVAL_REASONS.includes(reason)) throw new Error('E_REMOVAL_REASON');
		if (!known.has(word)) throw new Error('E_REMOVAL_UNKNOWN_WORD');
		if (removed.has(word)) throw new Error('E_REMOVAL_DUPLICATE');
		removed.add(word);
	}
	return removed;
}

/**
 * @param {readonly string[]} sourceWords
 * @param {ReadonlySet<string>} removed
 * @param {number} [minWords] only a test passes a smaller bound
 * @returns {string[]} the kept words, sorted by code unit
 */
export function curateWords(sourceWords, removed, minWords = MIN_WORDS) {
	const kept = sourceWords.filter((word) => !removed.has(word));
	kept.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
	// Checked before the count: a hyphenated word left in is the reviewer's mistake, and says so.
	if (!kept.every((word) => LETTERS.test(word))) throw new Error('E_CURATED_NOT_LETTERS');
	if (kept.length < minWords) throw new Error('E_TOO_FEW_WORDS');
	return kept;
}

/**
 * The module's source before prettier. The words are one string, not an array literal, which saves the
 * quotes and commas of every word before compression.
 * @param {readonly string[]} words
 * @returns {string}
 */
export function renderWordsModule(words) {
	// Only plain letters may reach the string literal, so nothing in it ever needs escaping.
	if (!words.every((word) => LETTERS.test(word))) throw new Error('E_CURATED_NOT_LETTERS');
	const text = words.join(LF);
	const sha256 = createHash('sha256').update(text, 'utf8').digest('hex');
	return [
		'/**',
		' * The backup word list, generated by `pnpm curate:backup-words` from the EFF Large Wordlist for',
		' * Passphrases (https://www.eff.org/dice, licence CC BY 4.0 per eff.org/copyright), minus the reviewed',
		' * removals in `content-ops/backup-words-removed.txt`. Do not edit by hand.',
		' *',
		' * Frozen for backup format v1: a changed list could refuse the words of an old backup, so a new',
		' * list ships only with a new format version.',
		' */',
		'',
		`export const WORDS_V1_TEXT = '${words.join(LF_ESCAPE)}';`,
		`export const WORDS_V1_SHA256 = '${sha256}';`,
		`export const WORDS_V1: readonly string[] = Object.freeze(WORDS_V1_TEXT.split('${LF_ESCAPE}'));`,
		''
	].join(LF);
}
