/**
 * The one recipe for the backup key worker's bytes, shared by the build script and the CI gate so the two can
 * never disagree about how the file is made or what it is called.
 *
 * Every option is fixed here and nothing about the machine reaches the output (no absolute path, no date, no
 * `define`), so the same source and the same esbuild release give the same bytes on any computer. The gate
 * rebuilds the file from source and compares it with the committed copy, which is what stops a changed worker
 * or word list from slipping into a release.
 */

import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { build } from 'esbuild';

export const KDF_FOLDER = 'static/backup-kdf';
export const KDF_FILE = 'backup-kdf.worker.mjs';

const ENTRY = 'src/lib/backup/worker/entry.ts';
const NOBLE_LICENSE = 'node_modules/@noble/hashes/LICENSE';
const HASH_LENGTH = 16;

/**
 * The MIT notice of the bundled `@noble/hashes`, as a leading `/*!` comment. MIT asks that the notice travel with
 * copies of the code, and esbuild keeps no notice for modules that carry none of their own. The text is read from
 * the installed package, so the build and the gate read the same file, and goes in unchanged.
 * @param {string} root
 * @returns {string}
 */
function nobleNotice(root) {
	const license = readFileSync(join(root, NOBLE_LICENSE), 'utf8');
	// A comment ends at its first closing mark, so a licence holding one could not be carried whole.
	if (license.includes('*/')) throw new Error('E_KDF_LICENSE_COMMENT_END');
	return `/*! @noble/hashes\n${license}\n*/\n`;
}

/**
 * The credit CC BY 4.0 asks for with copies of the bundled word list: the creator, the licence and a note that the
 * list was changed. The removed-word count is the line count of `backup-words-removed.txt`, and NOTICE states the
 * same count.
 */
const WORD_LIST_CREDIT =
	'/*! EFF Large Wordlist for Passphrases, Electronic Frontier Foundation, https://www.eff.org/dice, ' +
	'CC BY 4.0 https://creativecommons.org/licenses/by/4.0/, changed: 147 words removed */\n';

/**
 * Bundle the worker entry in memory.
 * @param {string} root the repository folder the entry path is resolved from
 * @returns {Promise<Uint8Array>} the bytes of the single output file
 */
export async function buildWorkerBytes(root) {
	const result = await build({
		entryPoints: [ENTRY],
		absWorkingDir: root,
		bundle: true,
		format: 'esm',
		platform: 'browser',
		target: 'es2022',
		minify: true,
		sourcemap: false,
		// Keeps any notice a bundled module carries itself in the shipped file.
		legalComments: 'eof',
		banner: { js: nobleNotice(root) + WORD_LIST_CREDIT },
		write: false,
		logLevel: 'silent'
	});
	const [file, ...others] = result.outputFiles;
	if (file === undefined || others.length > 0) throw new Error('E_KDF_BUILD_OUTPUT');
	return file.contents;
}

/**
 * The first 16 lowercase hex characters of the bytes' SHA-256: the folder name the file is served from.
 * @param {Uint8Array} bytes
 * @returns {string}
 */
export function workerHash(bytes) {
	return createHash('sha256').update(bytes).digest('hex').slice(0, HASH_LENGTH);
}

/**
 * The URL the app loads the worker from, for a given hash.
 * @param {string} hash
 * @returns {string}
 */
export function expectedWorkerSrc(hash) {
	return `/backup-kdf/${hash}/${KDF_FILE}`;
}

/**
 * The exact source of `src/lib/backup/kdf-paths.ts` for a worker URL. The build writes it and the gate compares the
 * committed file with it whole, so a second export, a comment or any other text in that file fails the gate. It is
 * written already in the form prettier leaves, so the commit hook never reformats it.
 * @param {string} src
 * @returns {string}
 */
export function pathsModule(src) {
	return [
		'/**',
		' * Where the backup key worker is served from. The hash in the folder name is the hash of the file, because a',
		' * cached file at a fixed URL is served forever: new bytes need a new URL. Generated by',
		' * `pnpm build:backup-kdf` and checked by `pnpm check:backup-vendor`; do not edit by hand.',
		' */',
		`export const KDF_WORKER_SRC = '${src}';`,
		''
	].join('\n');
}
